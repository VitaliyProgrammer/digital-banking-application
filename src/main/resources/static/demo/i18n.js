const LANG_KEY = 'lang';
const LOCALES = { uk: 'uk-UA', en: 'en-US' };
const CURRENCY_SIGNS = { UAH: '₴', USD: '$', EUR: '€' };

let lang = (() => {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && I18N[saved]) return saved;
    } catch { /* storage blocked */ }
    return 'uk';
})();

function currentLang() {
    return lang;
}

/** A text by its key; {name} placeholders are filled from params. Falls back to English, then to the key itself. */
function t(key, params = {}) {
    const text = I18N[lang][key] ?? I18N.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => (name in params ? params[name] : `{${name}}`));
}

/** The name of a code such as COMPLETED or UNIVERSAL; an unknown code is shown as it is. */
function label(code) {
    return (code && (LABELS[lang][code] ?? LABELS.en[code])) || code || '—';
}

/** "04.11.2026, 00:29" / "Nov 4, 2026, 00:29": a moment from the API (UTC) shown in Kyiv time. */
function formatDateTime(iso) {
    if (!iso) return '—';
    const options = lang === 'uk'
        ? { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' }
        : { month: 'short', day: 'numeric', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' };
    return new Date(iso).toLocaleString(LOCALES[lang], { ...options, timeZone: 'Europe/Kyiv' });
}

/**
 * "19.02.2027" / "Feb 19, 2027": a calendar day from the API ("2027-02-19"). Read as UTC midnight and written in UTC,
 * so no time zone can move it to the day before.
 */
function formatDate(isoDate) {
    if (!isoDate) return '—';
    const [year, month, dayOfMonth] = isoDate.split('-').map(Number);
    const options = lang === 'uk'
        ? { day: '2-digit', month: '2-digit', year: 'numeric' }
        : { month: 'short', day: 'numeric', year: 'numeric' };
    return new Date(Date.UTC(year, month - 1, dayOfMonth)).toLocaleDateString(LOCALES[lang], { ...options, timeZone: 'UTC' });
}

/** "1 250,40 ₴" / "1,250.40 ₴". */
function formatMoney(amount, currency = '') {
    if (amount == null) return '—';
    const number = Number(amount).toLocaleString(LOCALES[lang], { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    return currency ? `${number} ${CURRENCY_SIGNS[currency] || currency}` : number;
}

/** "41,47" / "41.47": a rate always with two decimals, like on an exchange board. */
function formatRate(rate) {
    if (rate == null) return '—';
    return Number(rate).toLocaleString(LOCALES[lang], { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

/** Puts the dictionary into the static page: data-i18n (content), data-i18n-title, data-i18n-placeholder. */
function applyStaticTexts() {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll('.lang-switch [data-lang]').forEach((button) => {
        const on = button.dataset.lang === lang;
        button.classList.toggle('on', on);
        button.setAttribute('aria-pressed', String(on));
    });
}

/** Switches the language at once: the static page here, the drawn views through the page's own hook. */
function setLang(next) {
    if (!I18N[next] || next === lang) return;
    lang = next;
    try { localStorage.setItem(LANG_KEY, next); } catch { /* storage blocked: only this page */ }
    applyStaticTexts();
    if (typeof onLanguageChanged === 'function') onLanguageChanged();
}

applyStaticTexts();
